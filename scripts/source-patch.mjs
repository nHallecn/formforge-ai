import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { transformWithEsbuild } from 'vite';
import { validateRepair } from './repair-contract.mjs';

export const SOURCE_PATH = 'src/fixtures/ScholarshipForm.jsx';
export const sha256 = text => createHash('sha256').update(text).digest('hex');

// This is a single-file, review-only source patcher. No arbitrary destination
// paths, no model-supplied code, no scripts run from untrusted repositories.
export function compileRepair(candidate) {
  validateRepair(candidate);
  const literal = JSON.stringify(candidate);
  return `import React, { useState } from 'react';

// Generated by FormForge from validated declarative data. Review before applying.
const spec = ${literal};
export default function ScholarshipForm() {
  const [submitted, setSubmitted] = useState(false);
  return <form onSubmit={event => { event.preventDefault(); setSubmitted(true); }}>
    <h2>{spec.formTitle}</h2>
    {spec.fields.map(field => <React.Fragment key={field.name}>
      <label htmlFor={'repaired-' + field.name}>{field.label}</label>
      {field.type === 'select'
        ? <select id={'repaired-' + field.name} name={field.name} required={field.required} defaultValue="">
          <option value="" disabled>Choose {field.label.toLowerCase()}</option>
          {field.options.map(option => <option key={option.value} value={option.value}>{option.label}</option>)}
        </select>
        : <input id={'repaired-' + field.name} name={field.name} type={field.type} required={field.required} />}
    </React.Fragment>)}
    <button type="submit">{spec.submitLabel}</button>
    <p role="status" aria-live="polite">{submitted ? spec.successMessage : ''}</p>
  </form>;
}
`;
}

export function unifiedDiff(oldText, newText, target = SOURCE_PATH) {
  if (target !== SOURCE_PATH) throw Error('Target must be the explicitly authorized fixture');
  const oldLines = oldText.replace(/\n$/, '').split('\n');
  const newLines = newText.replace(/\n$/, '').split('\n');
  return '--- a/' + target + '\n+++ b/' + target +
    '\n@@ -1,' + oldLines.length + ' +1,' + newLines.length + ' @@\n' +
    oldLines.map(line => '-' + line).join('\n') + '\n' +
    newLines.map(line => '+' + line).join('\n') + '\n';
}

export async function prepareSourcePatch(candidate, { root = resolve(new URL('../', import.meta.url).pathname) } = {}) {
  const originalPath = resolve(root, SOURCE_PATH);
  const original = await readFile(originalPath, 'utf8');
  if (!original.includes('export default function ScholarshipForm()') ||
      !original.includes('type="button"') ||
      !original.includes('name="fullName"') ||
      !original.includes('name="email"') ||
      !original.includes('name="program"')) {
    throw Error('Fixture preconditions changed; refuse to generate patch');
  }
  const generated = compileRepair(candidate);
  // Syntax compile is necessary but not sufficient. Browser verification is next.
  await transformWithEsbuild(generated, 'ScholarshipForm.jsx', { loader: 'jsx' });
  const outputDir = resolve(root, 'repair-artifacts');
  await mkdir(outputDir, { recursive: true });
  const patch = unifiedDiff(original, generated);
  // A preview imports the GENERATED MODULE, not the JSON-driven CandidateForm.
  const previewEntry = `import React from 'react';
import { createRoot } from 'react-dom/client';
import ScholarshipForm from './ScholarshipForm.jsx';
createRoot(document.getElementById('generated-root')).render(
  <main><h1>Generated source verification</h1><ScholarshipForm /></main>
);
`;
  const previewHTML = `<!doctype html>
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>FormForge generated source verification</title></head>
<body><div id="generated-root"></div><script type="module" src="/repair-artifacts/preview-entry.jsx"></script></body></html>
`;
  await transformWithEsbuild(previewEntry, 'preview-entry.jsx', { loader: 'jsx' });
  const manifest = {
    version: 1, mode: 'review_only', target: SOURCE_PATH,
    originalSha256: sha256(original), candidateSha256: sha256(generated),
    patchSha256: sha256(patch), previewSha256: sha256(previewHTML),
    previewEntrySha256: sha256(previewEntry), generatedWith: 'validated_template',
    checks: { schema: true, jsxSyntax: true, browser: false },
    approved: false,
  };
  await writeFile(resolve(outputDir, 'ScholarshipForm.jsx'), generated, { mode: 0o600 });
  await writeFile(resolve(outputDir, 'ScholarshipForm.patch'), patch, { mode: 0o600 });
  await writeFile(resolve(outputDir, 'preview.html'), previewHTML, { mode: 0o600 });
  await writeFile(resolve(outputDir, 'preview-entry.jsx'), previewEntry, { mode: 0o600 });
  await writeFile(resolve(outputDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', { mode: 0o600 });
  return manifest;
}
